"""In-Memory Mutable Mock IT Environment for POC testing."""
from typing import Literal, Dict, Any


class MockITEnvironment:
    def __init__(self):
        self.reset()

    def reset(
        self,
        vpn_connected: bool = False,
        certificate_valid: bool = True,
        password_status: Literal["active", "expired", "locked"] = "expired",
        vpn_service_healthy: bool = True,
    ):
        self.vpn_connected: bool = vpn_connected
        self.certificate_valid: bool = certificate_valid
        self.password_status: Literal["active", "expired", "locked"] = password_status
        self.vpn_service_healthy: bool = vpn_service_healthy

        # Stores the temporary password generated by the password-reset tool.
        self.temp_password: str | None = None

        self.last_action: str = "Environment reset to initial state"

    def get_state(self) -> Dict[str, Any]:
        return {
            "vpn_connected": self.vpn_connected,
            "certificate_valid": self.certificate_valid,
            "password_status": self.password_status,
            "vpn_service_healthy": self.vpn_service_healthy,
            "temp_password": self.temp_password,
            "last_action": self.last_action,
        }


# Global singleton in-memory environment
mock_environment = MockITEnvironment()